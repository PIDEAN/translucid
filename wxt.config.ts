import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import license from 'rollup-plugin-license';
import { defineConfig } from 'wxt';

import { bundledPackageRoots, completeDependencyLicenses, type DependencyLicense as Dep } from './src/build/third-party';

// Every bundle WXT builds (background, content scripts, pages) reports its own
// third-party modules; merge them and keep the full license texts, which MIT
// and Apache-2.0 require to travel with distributed copies.
const thirdParty = new Map<string, Dep>();
function collectLicenses(deps: Dep[]): void {
  for (const d of deps) if (d.name) {
    const key = `${d.name}@${d.version}`;
    const previous = thirdParty.get(key);
    thirdParty.set(key, { ...d, licenseText: d.licenseText || previous?.licenseText || null, noticeText: d.noticeText || previous?.noticeText || null });
  }
}

function writeNotices(list: Dep[], outDir: string): void {
  const repo = (d: Dep) => (typeof d.repository === 'string' ? d.repository : d.repository?.url ?? '');
  const body = list
    .map((d) => [`## ${d.name} ${d.version}`, `License: ${d.license ?? 'UNKNOWN'}`, repo(d) ? `Source: ${repo(d)}` : '', '', d.licenseSource ? `License source: ${d.licenseSource}` : '', '', d.licenseText!.trim(), d.noticeText ? `\nNOTICE:\n${d.noticeText.trim()}` : ''].filter((l) => l !== null).join('\n'))
    .join('\n\n---\n\n');
  // Some Apache-2.0 packages ship only the short header; include the license itself once (section 4a).
  const apache = list.some((d) => d.license === 'Apache-2.0')
    ? `\n\n---\n\n## Apache License, Version 2.0 (full text)\n\n${readFileSync('licenses/Apache-2.0.txt', 'utf8').trim()}`
    : '';
  const text = `Third-party software bundled in Translucid\n\nGenerated at build time from the modules included in the extension.\n\n${body}${apache}\n`;
  mkdirSync(outDir, { recursive: true });
  writeFileSync(`${outDir}/THIRD_PARTY_NOTICES.txt`, text);
  writeFileSync('THIRD_PARTY_NOTICES.md', `# ${text}`);
}

export default defineConfig({
  srcDir: '.',
  // Visible folder: macOS file pickers hide dot-folders such as the default .output.
  outDir: 'dist',
  // Same folder for every mode: an unpacked extension's ID (and its stored API keys) follows its path.
  outDirTemplate: '{{browser}}-mv{{manifestVersion}}',
  vite: () => ({ plugins: [license({ thirdParty: { includePrivate: false, output: collectLicenses as never } })] }),
  hooks: {
    'build:before': () => { thirdParty.clear(); },
    'build:done': (wxt, output) => {
      const modules = output.steps.flatMap((step) => step.chunks.flatMap((chunk) => chunk.type === 'chunk' ? chunk.moduleIds : []));
      const deps = completeDependencyLicenses([...thirdParty.values()], bundledPackageRoots(modules), 'licenses')
        .sort((a, b) => a.name!.localeCompare(b.name!));
      writeNotices(deps, wxt.config.outDir);
      output.publicAssets.push({ type: 'asset', fileName: 'THIRD_PARTY_NOTICES.txt' });
    },
  },
  manifest: {
    name: 'Translucid 透译',
    description: '用大模型把网页翻译成中文（双语对照 / 只看译文），并为网页应用生成任意语言的本地界面语言包',
    // scripting + unlimitedStorage: site language packs (runtime-registered content script, packs kept locally).
    permissions: ['storage', 'unlimitedStorage', 'contextMenus', 'tabs', 'scripting'],
    // The service worker calls arbitrary OpenAI-compatible endpoints.
    host_permissions: ['<all_urls>'],
    // Toolbar icon (concept A "双行"); generated by `pnpm icons` from src/ui/brand.ts.
    action: {
      default_icon: { 16: 'icon/16.png', 32: 'icon/32.png', 48: 'icon/48.png', 128: 'icon/128.png' },
    },
    commands: {
      'toggle-translate': {
        suggested_key: { default: 'Alt+A' },
        description: '翻译 / 恢复当前页面',
      },
      'toggle-mode': {
        suggested_key: { default: 'Alt+S' },
        description: '切换双语对照 / 替换原文',
      },
      'pick-regions': {
        suggested_key: { default: 'Alt+Shift+P' },
        description: '站点本地化：在当前网页开始圈选（不打开菜单，已展开的网页菜单保持打开）',
      },
    },
  },
});
